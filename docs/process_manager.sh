# Просмотреть все запущенные процессы
ps aux

# Найти процесс по имени
ps aux | grep process_name

# Завершить процесс по его PID
kill <PID>

# Принудительно завершить процесс
kill -9 <PID>

# Просмотреть использование ресурсов системы (CPU, RAM)
top

# Альтернатива top с более удобным интерфейсом
htop

# Проверить, какой процесс использует определённый порт
sudo lsof -i :port_number

# Проверить, какие процессы занимают больше всего памяти
ps aux --sort=-%mem | head

# Проверить, какие процессы занимают больше всего CPU
ps aux --sort=-%cpu | head